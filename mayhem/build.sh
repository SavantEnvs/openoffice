#!/usr/bin/env bash
#
# mayhem/build.sh — build the OpenOffice fuzz harnesses and the selftest oracle.
#
# AOO's own build (autoconf + dmake + hundreds of modules) is not usable here, so the few library
# sources the harnesses exercise are compiled directly: sal (the C runtime layer), sdext's pdfparse
# and vcl's fontsubset (sft/ttcr/cff/...). Nothing in the upstream tree is modified; the shims in
# mayhem/shim only supply headers that the 2008-era sources expect from the original build.
set -euo pipefail

[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH

: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${COVERAGE_FLAGS=}"
export SANITIZER_FLAGS DEBUG_FLAGS CC CXX LIB_FUZZING_ENGINE MAYHEM_JOBS COVERAGE_FLAGS

SRC="${SRC:-/mayhem}"
cd "$SRC"
M=$SRC/main
SH=$SRC/mayhem/shim
B=$SRC/mayhem/build
rm -rf "$B"
mkdir -p "$B"

SAL_DEFS="-DUNX -DLINUX -DGCC -DX86_64 -DCPPU_ENV=gcc3 -D_REENTRANT -DNO_PCH -DSAL_DLLIMPLEMENTATION -DRTL_OS=\"Linux\" -DRTL_ARCH=\"X86_64\" -D_FILE_OFFSET_BITS=64 -DOSL_DEBUG_LEVEL=0 -DSUPD=0 -include $SH/aoo_prelude.h"
PDF_DEFS="-DUNX -DLINUX -DGCC -DX86_64 -DCPPU_ENV=gcc3 -D_REENTRANT -DNO_PCH -DBOOST_SPIRIT_USE_OLD_NAMESPACE -DBOOST_SYSTEM_NO_DEPRECATED -DSYSTEM_ZLIB"
VCL_DEFS="-DUNX -DLINUX -DGCC -DX86_64 -DCPPU_ENV=gcc3 -D_REENTRANT -DNO_PCH -DVCL_INTERNALS -DOSL_DEBUG_LEVEL=0 -DSUPD=0 -include $SH/aoo_prelude.h"
SAL_INC="-I$M/sal/osl/all -I$M/sal/osl/inc -I$SH -I$B/gen -I$M/sal/inc -I$M/sal -I$M/sal/rtl/source -I$M/sal/osl/unx -I$M/sal/textenc"
PDF_INC="-I$B/gen -I$M/sal/inc -I$M/sdext/source/pdfimport/inc -I$SH"
VCL_INC="-I$SH -I$B/gen -I$M/sal/inc -I$M/vcl/inc -I$M/vcl/inc/vcl -I$M/tools/inc -I$M/comphelper/inc -I$M/vcl/source/fontsubset"
FONTSUBSET=$M/vcl/source/fontsubset
PDFDIR=$M/sdext/source/pdfimport/pdfparse

# sal/typesizes.h is generated by upstream's typesconfig tool during its own build.
mkdir -p "$B/gen/sal"
$CC -w "$M/sal/typesconfig/typesconfig.c" -o "$B/typesconfig"
"$B/typesconfig" "$B/gen/sal/typesizes.h" >/dev/null

sal_sources() {
  local d f
  d=$M/sal/rtl/source
  for f in memory cipher crc digest random locale strimp hash string ustring strbuf ustrbuf uuid rtl_process byteseq uri bootstrap cmdargs unload logfile tres debugprint math alloc_global alloc_cache alloc_arena; do echo "$d/$f"; done
  d=$M/sal/osl/unx
  for f in conditn diagnose interlck mutex nlsupport thread time util; do echo "$d/$f"; done
  d=$M/sal/osl/all
  for f in debugbase filepath loadmodulerelative printtrace utility; do echo "$d/$f"; done
  d=$M/sal/textenc
  for f in context convertbig5hkscs converter converteuctw convertgb18030 convertiso2022cn convertiso2022jp convertiso2022kr convertsinglebytetobmpunicode tcvtbyte tcvtmb tcvtutf7 tcvtutf8 tenchelp tencinfo textcvt textenc unichars; do echo "$d/$f"; done
}

# Relaxed UBSan checks, on the project's own objects only: the 2008-era code calls functions through
# pointers of a different (but ABI-compatible) type everywhere (-fsanitize=function), and sal's string
# hash relies on wrapping signed multiplication (strtmpl.c); memcpy(dst, NULL, 0) is used for empty
# records (ttcr.cxx name table). ASan and the rest of UBSan stay halting.
CALL_RELAX="-fno-sanitize=function,nonnull-attribute"
SAL_RELAX="-fno-sanitize=function,nonnull-attribute,signed-integer-overflow"

# compile_one <variant-dir> <flags> <defs> <inc> <source-without-extension>
compile_one() {
  local out=$1 flags=$2 defs=$3 inc=$4 base=$5 n
  n=$(basename "$base")
  if [ -f "$base.c" ]; then
    # shellcheck disable=SC2086
    $CC -w -fPIC $flags $defs $inc -c "$base.c" -o "$out/$n.o"
  else
    # shellcheck disable=SC2086
    $CXX -std=c++14 -w -fPIC $flags $defs $inc -c "$base.cxx" -o "$out/$n.o"
  fi
}
export -f compile_one

# build_variant <name> <flags>: static libraries libsal.a, libpdfparse.a, libfontsubset.a
build_variant() {
  local name=$1 flags=$2 out=$B/$1
  mkdir -p "$out/sal" "$out/pdf" "$out/vcl"
  sal_sources | xargs -P "$MAYHEM_JOBS" -I{} bash -c "compile_one '$out/sal' '$flags $SAL_RELAX' '$SAL_DEFS' '$SAL_INC' {}"
  rm -f "$out/libsal.a"; ar rcs "$out/libsal.a" "$out"/sal/*.o
  for f in pdfparse pdfentries; do echo "$PDFDIR/$f"; done | xargs -P "$MAYHEM_JOBS" -I{} bash -c "compile_one '$out/pdf' '$flags $CALL_RELAX' '$PDF_DEFS' '$PDF_INC' {}"
  rm -f "$out/libpdfparse.a"; ar rcs "$out/libpdfparse.a" "$out"/pdf/*.o
  for f in sft ttcr gsub xlat list cff fontsubset; do echo "$FONTSUBSET/$f"; done | xargs -P "$MAYHEM_JOBS" -I{} bash -c "compile_one '$out/vcl' '$flags $CALL_RELAX' '$VCL_DEFS' '$VCL_INC' {}"
  rm -f "$out/libfontsubset.a"; ar rcs "$out/libfontsubset.a" "$out"/vcl/*.o
}

# 1) the project's code, sanitized + instrumented for the fuzzers
build_variant fuzz "-O1 $SANITIZER_FLAGS $DEBUG_FLAGS -fsanitize=fuzzer-no-link"

# 2) each harness twice: libFuzzer, and the standalone one-input reproducer
$CC $SANITIZER_FLAGS $DEBUG_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$B/standalone_main.o"
$CXX $SANITIZER_FLAGS $DEBUG_FLAGS -c "$SRC/mayhem/lsan_off.cc" -o "$B/lsan_off.o"

LIBS="-lz -lpthread -ldl -lm"
build_harness() {
  local name=$1 defs=$2 inc=$3; shift 3
  local libs=("$@")
  # shellcheck disable=SC2086
  $CXX -std=c++14 -w $SANITIZER_FLAGS $DEBUG_FLAGS -fsanitize=fuzzer-no-link $defs $inc \
      -c "$SRC/mayhem/$name/$name.cpp" -o "$B/$name.o"
  # shellcheck disable=SC2086
  $CXX $SANITIZER_FLAGS $DEBUG_FLAGS $LIB_FUZZING_ENGINE "$B/$name.o" "$B/lsan_off.o" \
      "${libs[@]}" $LIBS -o "$SRC/$name"
  # shellcheck disable=SC2086
  $CXX $SANITIZER_FLAGS $DEBUG_FLAGS -fsanitize=fuzzer-no-link "$B/$name.o" "$B/standalone_main.o" "$B/lsan_off.o" \
      "${libs[@]}" $LIBS -o "$SRC/$name-standalone"
}
build_harness fuzz_pdfparse "$PDF_DEFS" "$PDF_INC" "$B/fuzz/libpdfparse.a" "$B/fuzz/libsal.a"
build_harness fuzz_sfnt "$VCL_DEFS" "$VCL_INC" "$B/fuzz/libfontsubset.a" "$B/fuzz/libsal.a"

# 3) the selftest oracle, built with normal flags (no sanitizers, no coverage runtime)
build_variant plain "-O1 $COVERAGE_FLAGS"
# shellcheck disable=SC2086
$CXX -std=c++14 -w -O1 $COVERAGE_FLAGS $VCL_DEFS $PDF_DEFS $VCL_INC $PDF_INC \
    "$SRC/mayhem/selftest.cpp" "$B/plain/libpdfparse.a" "$B/plain/libfontsubset.a" "$B/plain/libsal.a" \
    $LIBS -o "$SRC/openoffice_selftest"
